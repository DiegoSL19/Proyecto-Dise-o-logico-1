module vending_system (
    input  logic       clk,
    input  logic       reset,
    input  logic       request_event,
    input  logic       restart_event,
    input  logic [1:0] product_sel_in,
    input  logic [9:0] credit_in,
    output logic [1:0] product_sel_reg,
    output logic       selection_valid,
    output logic       product_valid,
    output logic [9:0] price_reg,
    output logic [9:0] credit_reg,
    output logic [1:0] inventory_A,
    output logic [1:0] inventory_B,
    output logic [1:0] inventory_C,
    output logic       empty_A,
    output logic       empty_B,
    output logic       empty_C,
    output logic [9:0] magnitude,
    output logic       negative,
    output logic       result_valid,
    output logic       selected_available,
    output logic       purchase_authorized,
    output logic       load_selection,
    output logic       load_price,
    output logic       load_credit,
    output logic       calculate_balance,
    output logic       decrement_A,
    output logic       decrement_B,
    output logic       decrement_C,
    output logic       clear_transaction
);

    vending_fsm fsm_inst (
        .clk(clk),
        .reset(reset),
        .request_event(request_event),
        .selection_valid(selection_valid),
        .product_sel_reg(product_sel_reg),
        .selected_available(selected_available),
        .result_valid(result_valid),
        .purchase_authorized(purchase_authorized),
        .restart_event(restart_event),
        .load_selection(load_selection),
        .load_price(load_price),
        .load_credit(load_credit),
        .calculate_balance(calculate_balance),
        .decrement_A(decrement_A),
        .decrement_B(decrement_B),
        .decrement_C(decrement_C),
        .clear_transaction(clear_transaction)
    );

    // Keep credit_in stable from request_event through the E0 load edge.
    transaction_integration transaction_integration_inst (
        .clk(clk),
        .reset(reset),
        .restart(clear_transaction),
        .load_selection(load_selection),
        .product_sel_in(product_sel_in),
        .credit_in(credit_in),
        .decrement_A(decrement_A),
        .decrement_B(decrement_B),
        .decrement_C(decrement_C),
        .load_price(load_price),
        .load_credit(load_credit),
        .calculate_balance(calculate_balance),
        .product_sel_reg(product_sel_reg),
        .selection_valid(selection_valid),
        .product_valid(product_valid),
        .price_reg(price_reg),
        .credit_reg(credit_reg),
        .inventory_A(inventory_A),
        .inventory_B(inventory_B),
        .inventory_C(inventory_C),
        .empty_A(empty_A),
        .empty_B(empty_B),
        .empty_C(empty_C),
        .magnitude(magnitude),
        .negative(negative),
        .result_valid(result_valid),
        .selected_available(selected_available),
        .purchase_authorized(purchase_authorized)
    );

endmodule
